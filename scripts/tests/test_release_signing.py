"""Release signatures (M3-21, ruling: an org-held Ed25519 key, SSH signature format).

Every key here is generated by the test: no signing service, no network. Our signatures
must verify with stock `ssh-keygen -Y verify`, so the org needs no tool of ours to check a
download."""

import os
import shutil
import subprocess
import sys
from pathlib import Path

import pytest
from cryptography.hazmat.primitives import serialization
from release_support import IDENTITY, allowed, new_key

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from agentic_release import signing  # noqa: E402


@pytest.fixture
def key(tmp_path: Path):
    path, public = new_key(tmp_path)
    return signing.load_private_key(path), public


def test_round_trip(key):
    private, public = key
    armored = signing.sign_bytes(private, b"wheel bytes")
    assert armored.startswith("-----BEGIN SSH SIGNATURE-----\n")
    signing.verify_bytes(b"wheel bytes", armored, signing.parse_allowed(allowed(public)), IDENTITY)


def test_tampered_file_fails(key):
    private, public = key
    armored = signing.sign_bytes(private, b"wheel bytes")
    with pytest.raises(signing.SignatureError, match="does not verify"):
        signing.verify_bytes(
            b"wheel bytez", armored, signing.parse_allowed(allowed(public)), IDENTITY
        )


def test_wrong_identity_or_namespace_fails(key):
    private, public = key
    signers = signing.parse_allowed(allowed(public))
    armored = signing.sign_bytes(private, b"x")
    with pytest.raises(signing.SignatureError, match="no allowed key"):
        signing.verify_bytes(b"x", armored, signers, "someone@example.invalid")
    other = signing.sign_bytes(private, b"x", namespace="file")
    with pytest.raises(signing.SignatureError, match="namespace"):
        signing.verify_bytes(b"x", other, signers, IDENTITY)
    narrowed = signing.parse_allowed(allowed(public, options='namespaces="git"'))
    with pytest.raises(signing.SignatureError, match="namespace"):
        signing.verify_bytes(b"x", armored, narrowed, IDENTITY)


def test_a_signature_by_another_key_fails(key, tmp_path: Path):
    private, public = key
    stranger, _ = new_key(tmp_path, "stranger")
    armored = signing.sign_bytes(signing.load_private_key(stranger), b"x")
    with pytest.raises(signing.SignatureError, match="no allowed key"):
        signing.verify_bytes(b"x", armored, signing.parse_allowed(allowed(public)), IDENTITY)


def test_unknown_allowed_signers_options_are_refused(key):
    """An expiry we would ignore must not silently pass (use ssh-keygen for those)."""
    _, public = key
    with pytest.raises(signing.SignatureError, match="valid-before"):
        signing.parse_allowed(allowed(public, options='valid-before="20260101"'))


def test_only_ed25519_keys_sign(tmp_path: Path):
    from cryptography.hazmat.primitives.asymmetric import ec

    path = tmp_path / "ecdsa"
    path.write_bytes(
        ec.generate_private_key(ec.SECP256R1()).private_bytes(
            serialization.Encoding.PEM,
            serialization.PrivateFormat.OpenSSH,
            serialization.NoEncryption(),
        )
    )
    with pytest.raises(signing.SignatureError, match="Ed25519"):
        signing.load_private_key(path)


def _ssh_keygen() -> str | None:
    found = shutil.which("ssh-keygen")
    if found is None and os.name == "nt":
        candidate = Path(os.environ.get("SystemRoot", r"C:\Windows")) / "System32"
        candidate = candidate / "OpenSSH" / "ssh-keygen.exe"
        found = str(candidate) if candidate.is_file() else None
    return found


@pytest.mark.skipif(_ssh_keygen() is None, reason="no ssh-keygen on this machine")
def test_ssh_keygen_verifies_our_signature(key, tmp_path: Path):
    private, public = key
    data = tmp_path / "agentic_core-1.0.0-py3-none-any.whl"
    data.write_bytes(b"PK\x03\x04 not really a wheel")
    sig = tmp_path / (data.name + ".sig")
    sig.write_text(signing.sign_bytes(private, data.read_bytes()), encoding="utf-8")
    signers = tmp_path / "allowed_signers"
    signers.write_text(allowed(public), encoding="utf-8")
    cmd = [_ssh_keygen(), "-Y", "verify", "-f", str(signers), "-I", IDENTITY]
    cmd += ["-n", signing.NAMESPACE, "-s", str(sig)]
    with data.open("rb") as stdin:
        done = subprocess.run(cmd, stdin=stdin, capture_output=True, text=True)
    assert done.returncode == 0, done.stderr
    assert "Good" in done.stdout


@pytest.mark.skipif(
    _ssh_keygen() is None or os.name == "nt",
    reason="ssh-keygen refuses a key file whose Windows ACL it cannot check",
)
def test_we_verify_a_signature_made_by_ssh_keygen(tmp_path: Path):
    path, public = new_key(tmp_path)
    path.chmod(0o600)
    data = tmp_path / "SHA256SUMS"
    data.write_bytes(b"abc  file\n")
    cmd = [_ssh_keygen(), "-Y", "sign", "-q", "-f", str(path), "-n", signing.NAMESPACE]
    subprocess.run([*cmd, str(data)], check=True, capture_output=True)
    armored = (tmp_path / "SHA256SUMS.sig").read_text(encoding="utf-8")
    signing.verify_bytes(
        data.read_bytes(), armored, signing.parse_allowed(allowed(public)), IDENTITY
    )


def release_dir(tmp_path: Path) -> Path:
    folder = tmp_path / "dist"
    folder.mkdir(parents=True)
    (folder / "agentic_cli-1.0.0-py3-none-any.whl").write_bytes(b"wheel")
    (folder / "agentic_cli-1.0.0.tar.gz").write_bytes(b"sdist")
    (folder / "agentic-sdlc-1.0.0.cdx.json").write_text("{}\n", encoding="utf-8")
    return folder


def test_a_signed_release_folder_verifies(key, tmp_path: Path):
    private, public = key
    folder = release_dir(tmp_path)
    signing.sign_dir(folder, private)
    sums = (folder / "SHA256SUMS").read_text(encoding="utf-8")
    assert sums.splitlines()[0].endswith("  agentic-sdlc-1.0.0.cdx.json")
    assert (folder / "SHA256SUMS.sig").is_file()
    verified = signing.verify_dir(folder, signing.parse_allowed(allowed(public)), IDENTITY)
    assert verified == sorted(p.name for p in release_dir(tmp_path / "again").iterdir())


@pytest.mark.parametrize("damage", ["edit", "extra", "missing-sig", "unlisted-sum"])
def test_a_damaged_release_folder_fails(key, tmp_path: Path, damage: str):
    private, public = key
    folder = release_dir(tmp_path)
    signing.sign_dir(folder, private)
    wheel = folder / "agentic_cli-1.0.0-py3-none-any.whl"
    if damage == "edit":
        wheel.write_bytes(b"wheel, changed after signing")
    elif damage == "extra":
        (folder / "planted.whl").write_bytes(b"x")
    elif damage == "missing-sig":
        (folder / (wheel.name + ".sig")).unlink()
    else:
        sums = folder / "SHA256SUMS"
        sums.write_text(sums.read_text(encoding="utf-8") + "0" * 64 + "  ghost.whl\n", "utf-8")
    with pytest.raises(signing.SignatureError):
        signing.verify_dir(folder, signing.parse_allowed(allowed(public)), IDENTITY)
